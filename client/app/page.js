'use client';

import React, { useState, useEffect, useCallback } from 'react';
import Navbar from '../components/Navbar';
import UserProfileHero from '../components/UserProfileHero';
import DevScoreCard from '../components/DevScoreCard';
import MetricsGrid from '../components/MetricsGrid';
import LanguageBreakdown from '../components/LanguageBreakdown';
import StrengthsAndTips from '../components/StrengthsAndTips';
import TopRepositories from '../components/TopRepositories';
import ActivityTimeline from '../components/ActivityTimeline';
import RepoAnalyzerView from '../components/RepoAnalyzerView';
import ShowdownView from '../components/ShowdownView';
import styles from '../styles/analyzer.module.css';
import { Search, Sparkles, Share2, Check } from 'lucide-react';

const API_BASE = process.env.NEXT_PUBLIC_API_URL || 'http://localhost:5000/api';

export default function Home() {
  const [activeTab, setActiveTab] = useState('profile');
  const [searchInput, setSearchInput] = useState('torvalds');
  const [profileData, setProfileData] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [rateLimit, setRateLimit] = useState(null);
  const [selectedRepo, setSelectedRepo] = useState('expressjs/express');
  const [copied, setCopied] = useState(false);

  const presets = ['torvalds', 'gaearon', 'shadcn', 'sindresorhus', 'leerob'];

  const fetchRateLimit = useCallback(async () => {
    try {
      const res = await fetch(`${API_BASE}/ratelimit`);
      if (res.ok) {
        const data = await res.json();
        setRateLimit(data);
      }
    } catch {
      // Fallback if backend is warming up
    }
  }, []);

  const analyzeUser = useCallback(async (userToQuery) => {
    const target = userToQuery || searchInput;
    if (!target || target.trim() === '') return;

    setLoading(true);
    setError(null);

    try {
      const res = await fetch(`${API_BASE}/user/${encodeURIComponent(target.trim())}`);
      const data = await res.json();

      if (!res.ok) {
        throw new Error(data.error || 'Failed to analyze GitHub user');
      }

      setProfileData(data);
      fetchRateLimit();
    } catch (err) {
      setError(err.message);
      setProfileData(null);
    } finally {
      setLoading(false);
    }
  }, [searchInput, fetchRateLimit]);

  // Initial load
  useEffect(() => {
    fetchRateLimit();
    analyzeUser('torvalds');
  }, [fetchRateLimit, analyzeUser]);

  function handleSearchSubmit(e) {
    e.preventDefault();
    analyzeUser();
  }

  function handlePresetClick(p) {
    setSearchInput(p);
    analyzeUser(p);
  }

  function handleDeepInspectRepo(repoFullName) {
    setSelectedRepo(repoFullName);
    setActiveTab('repo');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  }

  function handleCopySummary() {
    if (!profileData) return;
    const summary = `🚀 GitHub Developer Profile Analysis for @${profileData.user.login}
⭐ DevScore: ${profileData.score.score}/100 (${profileData.score.rank})
🌟 Total Stars: ${profileData.metrics.totalStars.toLocaleString()}
📦 Public Repos: ${profileData.user.publicReposCount} (${profileData.metrics.originalReposCount} original)
👥 Followers: ${profileData.user.followersCount.toLocaleString()}
💻 Top Languages: ${profileData.languages.slice(0, 3).map((l) => `${l.name} (${l.percentage}%)`).join(', ')}
Generated by GitPulse Pro`;

    navigator.clipboard.writeText(summary);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  }

  return (
    <div>
      <Navbar
        activeTab={activeTab}
        setActiveTab={setActiveTab}
        rateLimit={rateLimit}
      />

      <main className={styles.mainContainer}>
        {activeTab === 'profile' && (
          <div>
            {/* Search Hero */}
            <section className={styles.searchHero}>
              <h1 className={styles.heroTitle}>
                Developer <span className="text-gradient">Intelligence</span> Suite
              </h1>
              <p className={styles.heroSubtitle}>
                Deep-dive into GitHub engineering profiles, quantify developer score, audit code stacks, and discover high-impact metrics.
              </p>

              <div className={styles.searchBoxWrapper}>
                <form className={styles.searchForm} onSubmit={handleSearchSubmit}>
                  <input
                    type="text"
                    placeholder="Enter any GitHub username (e.g. torvalds, gaearon)"
                    value={searchInput}
                    onChange={(e) => setSearchInput(e.target.value)}
                    className={styles.searchInput}
                  />
                  <button type="submit" className={styles.searchSubmitBtn} disabled={loading}>
                    <Search size={16} />
                    <span>{loading ? 'Analyzing...' : 'Analyze'}</span>
                  </button>
                </form>

                <div className={styles.presetsList}>
                  <span className={styles.presetLabel}>Quick Demo Presets:</span>
                  {presets.map((p) => (
                    <button
                      key={p}
                      className={styles.presetChip}
                      onClick={() => handlePresetClick(p)}
                    >
                      @{p}
                    </button>
                  ))}
                </div>
              </div>

              {profileData && (
                <div style={{ marginTop: 14 }}>
                  <button
                    onClick={handleCopySummary}
                    style={{
                      display: 'inline-flex',
                      alignItems: 'center',
                      gap: 6,
                      fontSize: '0.82rem',
                      color: copied ? 'var(--accent-emerald)' : 'var(--accent-cyan)',
                      background: 'rgba(255, 255, 255, 0.04)',
                      padding: '6px 14px',
                      borderRadius: 'var(--radius-full)',
                      border: '1px solid var(--border-subtle)',
                    }}
                  >
                    {copied ? <Check size={14} /> : <Share2 size={14} />}
                    <span>{copied ? 'Summary Copied to Clipboard!' : 'Share / Copy Profile Report'}</span>
                  </button>
                </div>
              )}
            </section>

            {error && <div className={styles.errorBox}>{error}</div>}

            {loading && (
              <div className={styles.stateContainer}>
                <div className={styles.loadingSpinner} />
                <p style={{ color: 'var(--text-secondary)' }}>
                  Fetching repositories, commit activity, and computing OctoScore...
                </p>
              </div>
            )}

            {profileData && !loading && (
              <div className={`${styles.dashboardGrid} animate-fade-in`}>
                {/* Left Column: Identity & DevScore */}
                <aside>
                  <UserProfileHero user={profileData.user} />
                  <DevScoreCard scoreData={profileData.score} />
                </aside>

                {/* Right Column: Statistics, Languages, Insights & Repos */}
                <div>
                  <MetricsGrid metrics={profileData.metrics} user={profileData.user} />
                  <LanguageBreakdown languages={profileData.languages} />
                  <StrengthsAndTips
                    strengths={profileData.strengths}
                    recommendations={profileData.recommendations}
                  />
                  <TopRepositories
                    repos={profileData.topStarredRepos}
                    onAnalyzeRepo={handleDeepInspectRepo}
                  />
                  <ActivityTimeline events={profileData.recentEvents} />
                </div>
              </div>
            )}
          </div>
        )}

        {activeTab === 'repo' && (
          <RepoAnalyzerView
            initialRepo={selectedRepo}
            apiUrl={API_BASE}
            onRateLimitUpdate={fetchRateLimit}
          />
        )}

        {activeTab === 'showdown' && (
          <ShowdownView
            apiUrl={API_BASE}
            onRateLimitUpdate={fetchRateLimit}
          />
        )}
      </main>
    </div>
  );
}
